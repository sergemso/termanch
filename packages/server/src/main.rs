#[derive(Parser, Debug)]
#[command(name = "termanch-server")]
struct Args {
    #[arg(long, env = "TERMANCH_HOST", default_value = "0.0.0.0")]
    host: String,

    #[arg(long, env = "TERMANCH_PORT", default_value = "8080")]
    port: u16,

    /// Where the owner, keys and certificate are kept (a volume in Docker). Default: ~/.config/termanch
    #[arg(long, env = "TERMANCH_CONFIG_DIR", default_value_os_t = default_config_dir())]
    config_dir: PathBuf,

    #[arg(long, env = "TERMANCH_SERVER_NAME", default_value = "termanch-server")]
    server_name: String,

    /// Client that opens the registration link.
    #[arg(
        long,
        env = "TERMANCH_CLIENT_URL",
        default_value = "https://app.termanch.vivantel.dev"
    )]
    client_url: String,

    /// Session manager: `tmux` (built in) or `command` (any CLI, see TERMANCH_BACKEND_*).
    #[arg(long, env = "TERMANCH_BACKEND", default_value = "tmux")]
    backend: String,

    /// For `command`: a label shown in logs, e.g. herdr.
    #[arg(long, env = "TERMANCH_BACKEND_NAME", default_value = "command")]
    backend_name: String,

    /// For `command`: prints one session per line (`id` or `id|name`).
    #[arg(long, env = "TERMANCH_BACKEND_LIST")]
    backend_list: Option<String>,

    /// For `command`: creates a detached session; `{name}` is replaced.
    #[arg(long, env = "TERMANCH_BACKEND_CREATE")]
    backend_create: Option<String>,

    /// For `command`: attaches a terminal to a session; `{id}` is replaced.
    #[arg(long, env = "TERMANCH_BACKEND_ATTACH")]
    backend_attach: Option<String>,

    /// Where sessions run: `container` (default, isolated) or `host` (needs --pid=host --privileged).
    #[arg(long, env = "TERMANCH_RUN", default_value = "container")]
    run: String,

    /// For `host`: the user sessions run as, `root` or a dedicated unprivileged user.
    #[arg(long, env = "TERMANCH_RUN_USER", default_value = "termanch")]
    run_user: String,

    /// UDP port of the WebRTC-direct transport (open it in the firewall).
    #[arg(long, env = "TERMANCH_UDP_PORT", default_value = "4443")]
    udp_port: u16,

    /// Address clients connect to over WebRTC; detected when not set.
    #[arg(long, env = "TERMANCH_PUBLIC_IP")]
    public_ip: Option<std::net::IpAddr>,

    /// Turn the WebRTC-direct transport off (WebSocket only).
    #[arg(long, env = "TERMANCH_WEBRTC", default_value = "on")]
    webrtc: String,

    /// Serve /rtc-info with the unsigned connection details. For development and tests only.
    #[arg(long, env = "TERMANCH_DEV_INFO", default_value = "off")]
    dev_info: String,

    /// One-time secret generated by the client and carried in the install command; claims the server.
    #[arg(long, env = "TERMANCH_CLAIM_SECRET")]
    claim_secret: Option<String>,

    /// Directory to announce to (defaults to the client's origin). Empty turns announcing off.
    #[arg(long, env = "TERMANCH_DIRECTORY_URL")]
    directory_url: Option<String>,

    /// One-shot, run by the installer on an existing install: start a new claim with this secret,
    /// replacing any owner. Whoever can run this has root on the host, which already allows the same.
    #[arg(long)]
    claim: Option<String>,

    /// With --register: draw the QR even when stdout is not a terminal (used through `docker exec`).
    #[arg(long, default_value = "false")]
    qr: bool,

    /// Print the registration link for this (unclaimed) server and exit.
    #[arg(long, default_value = "false")]
    register: bool,
}

#[derive(Clone)]
pub struct AppState {
    pub auth: Arc<AuthState>,
    pub sessions: Arc<SessionManager>,
    pub server_name: String,
    /// `container` or `host:<user>`, shown to the owner.
    pub mode: String,
    pub rtc_info: Option<rtc::RtcInfo>,
}

fn default_config_dir() -> PathBuf {
    std::env::var_os("HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("/var/lib"))
        .join(".config/termanch")
}

fn build_backend(args: &Args, mode: &RunMode) -> anyhow::Result<Arc<dyn SessionBackend>> {
    match args.backend.as_str() {
        "tmux" => Ok(Arc::new(TmuxBackend::new(mode.runner()))),
        "command" => {
            let need = |v: &Option<String>, name: &str| {
                v.clone()
                    .ok_or_else(|| anyhow::anyhow!("TERMANCH_BACKEND=command needs {name}"))
            };
            Ok(Arc::new(CommandBackend::with_runner(
                &args.backend_name,
                &need(&args.backend_list, "TERMANCH_BACKEND_LIST")?,
                &need(&args.backend_create, "TERMANCH_BACKEND_CREATE")?,
                &need(&args.backend_attach, "TERMANCH_BACKEND_ATTACH")?,
                mode.runner(),
            )?))
        }
        other => Err(anyhow::anyhow!(
            "unknown TERMANCH_BACKEND `{other}` (tmux or command)"
        )),
    }
}

fn print_registration(args: &Args, auth: &AuthState) -> anyhow::Result<()> {
    use std::io::IsTerminal;
    if let Some(owner) = auth.owner() {
        println!("This server is registered to @{}.", owner.login);
        // A browser that forgot the server (removed it, or a new device) can add it again by id: no secret needed.
        let id = directory::ServerKey::load_or_create(&args.config_dir)?.server_id();
        let link = auth::server_link(&args.client_url, &id);
        if args.qr || std::io::stdout().is_terminal() {
            if let Some(qr) = auth::claim_qr(&link) {
                println!("{qr}");
            }
        }
        println!(
            "To add it to a browser signed in as @{}, scan the code or open:\n\n  {link}\n",
            owner.login
        );
        return Ok(());
    }
    let claim = auth
        .claim_token()?
        .ok_or_else(|| anyhow::anyhow!("no claim token"))?;
    let link = auth::claim_link(&args.client_url, &claim);
    if args.qr || std::io::stdout().is_terminal() {
        if let Some(qr) = auth::claim_qr(&link) {
            println!("{qr}");
        }
    }
    println!("Scan the code with Termanch (or your phone's camera), or open:\n\n  {link}\n");
    println!(
        "The first GitHub user to connect becomes the owner. The code works for 15 minutes, once."
    );
    Ok(())
}

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| tracing_subscriber::EnvFilter::new("info")),
        )
        .init();

    let args = Args::parse();
    // An uninstalled server that Docker restarted stays idle instead of coming back as a new unclaimed
    // server; the installer's --claim removes the marker, which ends the idle wait so Docker restarts it.
    if args.claim.is_none() && !args.register && uninstall::is_uninstalled(&args.config_dir) {
        println!("This server was uninstalled. Remove its container, or run the installer again to set it up.");
        while uninstall::is_uninstalled(&args.config_dir) {
            tokio::time::sleep(std::time::Duration::from_secs(2)).await;
        }
        return Ok(());
    }

    let keys = cert::CertKeys::from_env()?;
    anyhow::ensure!(
        !keys.is_empty(),
        "no certificate keys configured (TERMANCH_CERT_KEYS)"
    );
    std::fs::create_dir_all(&args.config_dir)?;
    let server_id = directory::ServerKey::load_or_create(&args.config_dir)?.server_id();
    let auth = Arc::new(AuthState::new(args.config_dir.clone(), keys, server_id)?);

    if let Some(secret) = &args.claim {
        auth.reclaim(secret)?;
        println!("Claim started; the server will announce it within seconds.");
        return Ok(());
    }

    if args.register {
        return print_registration(&args, &auth);
    }

    if let Some(secret) = &args.claim_secret {
        auth.provide_claim(secret)?;
    }

    match auth.owner() {
        Some(owner) => info!("Server owner: @{}", owner.login),
        None => {
            auth.claim_token()?;
            info!("Server is unclaimed; run `termanch-server --register` to get the registration link");
        }
    }

    let mode = RunMode::parse(&args.run, &args.run_user)?;
    mode.self_check()
        .await
        .map_err(|e| anyhow::anyhow!("TERMANCH_RUN={}: {e}", mode.label()))?;
    if mode.is_host() {
        info!(target: "audit", event = "host_mode_enabled", user = %mode.label());
    }
    let backend = build_backend(&args, &mode)?;
    info!("Session backend: {}", backend.name());
    let mut state = AppState {
        auth,
        sessions: Arc::new(SessionManager::new(backend, mode.clone()).with_uninstall(
            args.server_name.clone(),
            Arc::new(|| {
                // Let the reply reach the client, then stop; Docker then finds the idle marker.
                std::thread::spawn(|| {
                    std::thread::sleep(std::time::Duration::from_secs(1));
                    std::process::exit(0);
                });
            }),
        )),
        server_name: args.server_name.clone(),
        mode: mode.label(),
        rtc_info: None,
    };

    if args.webrtc != "off" {
        let http = reqwest::Client::builder()
            .timeout(std::time::Duration::from_secs(5))
            .build()?;
        let public_ip = match args.public_ip {
            Some(ip) => ip,
            None => netutil::discover_public_ip(&http).await.ok_or_else(|| {
                anyhow::anyhow!("cannot find this host's public IP; set TERMANCH_PUBLIC_IP")
            })?,
        };
        let cert = rtc::load_or_create_cert(&args.config_dir)?;
        let bind = SocketAddr::new(std::net::Ipv4Addr::UNSPECIFIED.into(), args.udp_port);
        let info = rtc::start(bind, public_ip, cert, rtc::Limits::default(), state.clone()).await?;
        info!(
            "WebRTC-direct on udp {}:{} ({})",
            info.ip, info.port, info.fingerprint
        );
        let origin = args
            .directory_url
            .clone()
            .unwrap_or_else(|| args.client_url.clone());
        if !origin.is_empty() {
            let key = Arc::new(directory::ServerKey::load_or_create(&args.config_dir)?);
            info!("Server id {}", key.server_id());
            tokio::spawn(directory::run(
                key,
                origin,
                info.clone(),
                String::new(),
                state.auth.clone(),
                http,
            ));
        }
        state.rtc_info = Some(info);
    }

    let app = router(state, args.dev_info == "on");

    let addr: SocketAddr = format!("{}:{}", args.host, args.port).parse()?;
    info!("Starting server on {}", addr);

    let listener = tokio::net::TcpListener::bind(addr).await?;
    axum::serve(listener, app).await?;

    Ok(())
}

/// No credentials cross origins here: the WebSocket authenticates in its first message.
fn router(state: AppState, dev_info: bool) -> Router {
    let mut app = Router::new()
        .route("/health", get(|| async { "OK" }))
        .route("/ws", get(ws_handler));
    if dev_info {
        app = app.route("/rtc-info", get(rtc_info));
    }
    app.layer(CorsLayer::permissive())
        .layer(TraceLayer::new_for_http())
        .with_state(state)
}

async fn rtc_info(
    State(state): State<AppState>,
) -> axum::response::Result<axum::Json<rtc::RtcInfo>> {
    state
        .rtc_info
        .map(axum::Json)
        .ok_or_else(|| axum::http::StatusCode::NOT_FOUND.into())
}

async fn ws_handler(
    ws: WebSocketUpgrade,
    State(state): State<AppState>,
    headers: HeaderMap,
) -> Response {
    ws.on_upgrade(|socket| handle_websocket(socket, State(state), headers))
}
